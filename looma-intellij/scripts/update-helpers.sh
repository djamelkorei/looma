#!/bin/sh
# Regenerates the list of built-in template helper methods from the compiled engine.
# Run after changing looma-core's helpers:  mvn -q -pl looma-core compile && looma-intellij/scripts/update-helpers.sh
set -e
cd "$(dirname "$0")/.."
classes=../looma-core/target/classes
out=src/main/resources/io/github/djamelkorei/looma/intellij/helpers.txt
echo "# Generated by scripts/update-helpers.sh from looma-core; do not edit." > "$out"
for helper in String Math Number Date List; do
  javap -public -cp "$classes" "io.github.djamelkorei.looma.helper.${helper}Helper" \
    | grep -E '^ +public [^(]+\(' | grep -v -E ' name\(\)|static|Helper\(' \
    | sed -E 's/^ +public //; s/;$//; s/java\.(lang|util|time)\.//g; s/io\.github\.djamelkorei\.looma\.//g' \
    | sed -E "s/^(.+) ([a-zA-Z0-9_]+)\((.*)\)$/$helper \2(\3): \1/" >> "$out"
done
